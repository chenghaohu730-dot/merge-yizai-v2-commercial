import { copyFile, mkdir, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import path from "node:path";

const projectRoot = path.resolve(import.meta.dirname, "..");
const require = createRequire(path.join(projectRoot, "game", "web-prototype", "package.json"));
const sharp = require("sharp");

const finalDir = path.join(projectRoot, "art", "final", "ui", "filing-systems");
const webDir = path.join(projectRoot, "game", "web-prototype", "public", "assets", "ui");
const wechatDir = path.join(projectRoot, "game", "wechat-minigame", "assets", "ui");
const generatedDir = path.join(projectRoot, "art", "generated", "filing-systems-ui");

